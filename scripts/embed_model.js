#!/usr/bin/env node
// Writes tests/e2e/data/model.json into src/core.js between the BLOCK_MODEL
// markers.   node tests/e2e/train.js && node scripts/embed_model.js
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const model = JSON.parse(fs.readFileSync(path.join(root, 'tests/e2e/data/model.json'), 'utf8'));
const core = path.join(root, 'src/core.js');
let s = fs.readFileSync(core, 'utf8');
const start = s.indexOf('  // BLOCK_MODEL:begin'), end = s.indexOf('  // BLOCK_MODEL:end');
if (start < 0 || end < 0) throw new Error('markers not found in src/core.js');
const body = '  // BLOCK_MODEL:begin (generated by scripts/embed_model.js from tests/e2e/data/model.json)\n  const BLOCK_MODEL = ' + JSON.stringify(model) + ';\n';
s = s.slice(0, start) + body + s.slice(end);
fs.writeFileSync(core, s);
console.log(`embedded ${model.type} model (${model.names.length} features${model.type === 'mlp' ? ', H=' + model.H : ''}, thr ${model.threshold}) into src/core.js`);
